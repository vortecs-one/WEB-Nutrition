export interface PublicDomainInfo {
  sourceWork: string;
  author: string;
  firstPublished: number;
  publicDomainSince: number;
  jurisdiction: "US";
  usageNotes: Localized;
}

/**
 * `low`: literary source, long in the public domain, no active studio claim on
 * the original design. `high`: animation-studio character whose owner still
 * holds active trademarks — artwork stays withheld until legal review.
 */
export type RightsRisk = "low" | "high";

/**
 * Setting of the animated popup: the idle motion, particles and ground. The
 * meadow takes its grass from the artwork's ground layers; the ice has a floor
 * drawn in code (see lib/pets/animations.ts).
 */
export type PetScene = "meadow" | "ice";

export interface PetLayers {
  body: string;
  ground?: string;
  back?: string;
  /** Full-body poses on the same canvas as `body` (sheet-drawn companions). */
  poses?: Partial<Record<PetPose, string>>;
  /** Close-up face per mood, for the dashboard card (not a popup layer). */
  faces?: Partial<Record<CharacterMood, string>>;
}

export interface VirtualCharacter {
  id: string;
  name: Localized;
  species: CharacterSpecies;
  temperament: CharacterTemperament;
  description: Localized;
  /** Public-domain source; absent for the app's own original characters. */
  rights?: PublicDomainInfo;
  /** Credit line for original characters (no public-domain source). */
  origin?: Localized;
  rightsRisk: RightsRisk;
  /**
   * Shown to everyone (locked) but selectable only by the accounts allowed in
   * lib/pets/access.ts; the server actions enforce it.
   */
  exclusive?: boolean;
  /** Original artwork drawn from the public-domain source; null while withheld. */
  artwork: string | null;
  /**
   * Animated-popup layers generated by scripts/cutout-pet.mjs, all on the same
   * canvas: `body` (the background-free character) moves; `ground` (static
   * grass or snow drawn in front of it) and `back` (ground filled in behind
   * the legs, revealed while it jumps) exist only for companions with a
   * ground split. Characters without layers show their static artwork.
   * Companions drawn on character sheets (scripts/pet-sheet.mjs) also have
   * `poses` and `faces`.
   */
  layers?: PetLayers;
  /** Animated-popup setting; "meadow" when absent. */
  scene?: PetScene;
  enabled: boolean;
}

export interface CharacterState {
  characterId: string;
  nickname: string | null;
  adoptedAt: string;
  updatedAt: string;
}

export type CharacterAction =
  | { type: "adopt"; characterId: string; at: string }
  | { type: "rename"; nickname: string | null; at: string }
  | { type: "release" };
